/**
 * 見出しの行の ⓘ から開く中身(2026-10-08 ユーザー指示「オプションのタブの近くに information アイコンおいてモーダルで上の表みたいなのを
 * 表示したい。結果の今のままとかのタブのところも」。同日、アカウント・組み直しプランの発動頻度の選び方・リソースのシートにも足した)。
 * 形は中身に合わせる: 違いがいくつもある 3 択は表(列 = 選択肢、行 = 違い)、言葉の意味が分かればよいものは名前と文、
 * 名前の要らないもの(シートの使い方)は文だけ。
 * **文は初見の人が分かるように書き、文ごとに改行しない**(同日ユーザー指示「文ごとの改行だるいかも。長くなるなら必要なら改行はありだけど。
 * 後文章は初見の人がわかるように書くこと」)— 1 つの段落にまとめ、長くなるときだけ段落を分ける。
 * 中身は計算の実装に合わせる: 前提の 3 択は `searchPremise.ts` / `OptimizerPanel` の `current*`、組み直すとは `engine/trueRanking.ts`
 */
export interface InfoTable<K extends string> {
  title: string;
  /** 表の前に置く 1 段落(表の中の言葉の意味を先に言うとき) */
  lead?: string;
  columns: readonly { key: K; label: string }[];
  rows: readonly { label: string; cells: readonly string[] }[];
}

export interface InfoTerms<K extends string> {
  title: string;
  /** 名前の並びの前に置く 1 段落(何の選び方かを先に言うとき) */
  lead?: string;
  /** 名前と、その下の段落(ふつうは 1 つ。長いときだけ分ける) */
  terms: readonly { key: K; label: string; paragraphs: readonly string[] }[];
}

/** 名前を持たない段落だけ(シートの使い方 — リソース) */
export interface InfoText {
  title: string;
  paragraphs: readonly string[];
}

